    private static void onChallengePlayerDeath(ServerPlayer player, DamageSource source) {
        if (!(player.level() instanceof ServerLevel level)) return;
        boolean inRange = false;
        WitherBoss killer = source.getEntity() instanceof WitherBoss wb
                && WitherTitleHelper.isUndefinedWither(wb) ? wb : null;
        for (WitherBoss wither : level.getEntitiesOfClass(WitherBoss.class,
                player.getBoundingBox().inflate(CHALLENGE_RANGE),
                WitherTitleHelper::isUndefinedWither)) {
            inRange = true;
            restoreUndefinedHealth(wither, 0.1F);
        }
        if (killer != null && killer.level() == level && killer.distanceTo(player) > CHALLENGE_RANGE) {
            restoreUndefinedHealth(killer, 0.1F);
        }
        if (inRange) {
            holdKeepInventory(level);
        }
    }

    private static void restoreUndefinedHealth(WitherBoss wither, float fraction) {
        if (!wither.isAlive() || wither.level().isClientSide) return;
        try {
            if (wither.getEntityData().get(WitherTitleHelper.UNDEFINED_FINAL_SKILL)) return;
        } catch (Throwable ignored) {
            return;
        }
        float next = Math.min(wither.getMaxHealth(),
                WitherTitleHelper.getHiddenHp(wither) + wither.getMaxHealth() * fraction);
        WitherTitleHelper.beginLegitWrite();
        try {
            wither.setHealth(next);
        } finally {
            WitherTitleHelper.endLegitWrite();
        }
        WitherTitleHelper.restoreDisplayHealth(wither, WitherTitleHelper.getHiddenHp(wither));
    }

    private static void holdKeepInventory(ServerLevel level) {
        GameRules.BooleanValue rule = level.getGameRules().getRule(GameRules.RULE_KEEPINVENTORY);
        if (rule.get() && keepInventoryHolds == 0) return;
        if (keepInventoryHolds == 0) {
            rule.set(true, level.getServer());
        }
        keepInventoryHolds++;
        int releaseAt = level.getServer().getTickCount() + 1;
        level.getServer().tell(new TickTask(releaseAt, () -> releaseKeepInventory(level)));
    }

    private static void releaseKeepInventory(ServerLevel level) {
        if (keepInventoryHolds <= 0) return;
        keepInventoryHolds--;
        if (keepInventoryHolds == 0) {
            level.getGameRules().getRule(GameRules.RULE_KEEPINVENTORY).set(false, level.getServer());
        }
    }

    private static void keepUndefinedChunkLoaded(WitherBoss wither, ServerLevel level) {
        ChunkPos pos = wither.chunkPosition();
        UUID id = wither.getUUID();
        ChunkPos prev = UNDEFINED_LOADED_CHUNK.get(id);
        ResourceKey<net.minecraft.world.level.Level> prevDim = UNDEFINED_LOADED_DIM.get(id);
        if (pos.equals(prev) && level.dimension().equals(prevDim)) return;
        releaseUndefinedChunk(id, level.getServer());
        level.getChunkSource().addRegionTicket(UNDEFINED_CHUNK_TICKET, pos, UNDEFINED_CHUNK_LEVEL, id);
        UNDEFINED_LOADED_CHUNK.put(id, pos);
        UNDEFINED_LOADED_DIM.put(id, level.dimension());
    }

    private static void releaseUndefinedChunk(UUID id, MinecraftServer server) {
        ChunkPos pos = UNDEFINED_LOADED_CHUNK.remove(id);
        ResourceKey<net.minecraft.world.level.Level> dim = UNDEFINED_LOADED_DIM.remove(id);
        if (pos == null || dim == null || server == null) return;
        ServerLevel level = server.getLevel(dim);
        if (level == null) return;
        level.getChunkSource().removeRegionTicket(UNDEFINED_CHUNK_TICKET, pos, UNDEFINED_CHUNK_LEVEL, id);
    }

    private static void applyChallengeZone(WitherBoss wither, ServerLevel level) {
        AABB box = wither.getBoundingBox().inflate(CHALLENGE_RANGE);
        for (ServerPlayer player : level.getEntitiesOfClass(ServerPlayer.class, box, p -> !p.isSpectator())) {
            if (player.isCreative()) {
                if (FLIGHT_LOCKED.remove(player.getUUID())) {
                    restoreChallengeFlight(player);
                }
                continue;
            }
            // A Soul Heart in the Star Corona explicitly bypasses the Undefined Wither's no-flight zone.
            if (StarCoronaCurios.hasSoulHeart(player)) {
                FLIGHT_LOCKED.remove(player.getUUID());
                if (!player.getAbilities().mayfly) {
                    player.getAbilities().mayfly = true;
                    player.onUpdateAbilities();
                }
                continue;
            }
            suppressChallengeFlight(player);
            FLIGHT_LOCKED.add(player.getUUID());
        }
    }

    private static void suppressChallengeFlight(ServerPlayer player) {
        if (player.getPersistentData().getBoolean(CHALLENGE_FLIGHT_LOCKED)) {
            restoreChallengeFlight(player);
        }
        if (!player.getAbilities().flying) return;
        player.getAbilities().flying = false;
        player.onUpdateAbilities();
    }

    private static void restoreChallengeFlight(ServerPlayer player) {
        CompoundTag data = player.getPersistentData();
        if (!data.getBoolean(CHALLENGE_FLIGHT_LOCKED)) return;
        player.getAbilities().mayfly = data.getBoolean(CHALLENGE_MAYFLY_SAVED);
        data.remove(CHALLENGE_FLIGHT_LOCKED);
        data.remove(CHALLENGE_MAYFLY_SAVED);
        player.onUpdateAbilities();
    }

    private static void releaseFlightOutsideChallenge(MinecraftServer server) {
        if (FLIGHT_LOCKED.isEmpty()) return;
        FLIGHT_LOCKED.removeIf(id -> {
            ServerPlayer player = server.getPlayerList().getPlayer(id);
            if (player == null) return true;
            if (!(player.level() instanceof ServerLevel level)) return false;
            boolean inside = !level.getEntitiesOfClass(WitherBoss.class,
                    player.getBoundingBox().inflate(CHALLENGE_RANGE),
                    WitherTitleHelper::isUndefinedWither).isEmpty();
            if (inside) return false;
            restoreChallengeFlight(player);
            return true;
        });
    }

    private static boolean smiteLockout(WitherBoss wither) {
        long expire = wither.getPersistentData().getLong(WitherTitleHelper.SMITE_EXPIRE_KEY);
        return expire > wither.level().getGameTime();
    }

