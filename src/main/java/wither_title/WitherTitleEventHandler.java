    private static void handleTitle6Sustain(WitherBoss wither) {
        CompoundTag data = wither.getPersistentData();
        if (!data.getBoolean(WitherTitleHelper.T6_FIRED_KEY)) {
            // 每只凋零仅触发一次：生命值降为一半时
            if (wither.getHealth() <= wither.getMaxHealth() * 0.5F) {
                data.putBoolean(WitherTitleHelper.T6_FIRED_KEY, true);
                boolean griefing = ForgeEventFactory.getMobGriefingEvent(wither.level(), wither);
                wither.level().explode(wither, wither.getX(), wither.getY(), wither.getZ(), 7.0F, false,
                        griefing ? Level.ExplosionInteraction.MOB : Level.ExplosionInteraction.NONE);
                for (int i = 0; i < 4; i++) {
                    summonWitherSkeleton(wither);
                }
            }
            return;
        }
        // 自身 10 格内存在 >=1 只该凋零的仆从骷髅时，每秒恢复 1 点生命值
        if (wither.tickCount % 20 != 0) return;
        List<WitherSkeleton> servants = wither.level().getEntitiesOfClass(WitherSkeleton.class,
                wither.getBoundingBox().inflate(10.0D),
                s -> WitherTitleHelper.isWitherServant(s, wither.getUUID()));
        if (!servants.isEmpty()) {
            wither.heal(1.0F);
            LivingEntity target = wither.getTarget();
            for (WitherSkeleton servant : servants) {
                // 纠偏：仆从绝不对主人产生仇恨（误伤反咬兜底）
                if (servant.getTarget() == wither) {
                    servant.setTarget(null);
                    servant.setLastHurtByMob(null);
                    continue;
                }
                if (target != null && servant.getTarget() == null) {
                    servant.setTarget(target);
                }
            }
        }
    }

    /**
     * 头衔6 仆从凋灵骷髅：
     * 认召唤的凋零为主人；自带 抗性提升I / 速度II / 生命恢复II（各30秒）；
     * 全套随机附魔钻石甲 + 随机附魔钻石剑；最大血量 60。
     */
    private static void summonWitherSkeleton(WitherBoss wither) {
        if (!(wither.level() instanceof ServerLevel serverLevel)) return;
        RandomSource random = serverLevel.getRandom();
        UndefinedWitherServant skeleton =
                new UndefinedWitherServant(WitherTitleEntities.UNDEFINED_WITHER_SERVANT.get(), serverLevel);
        skeleton.setPos(wither.getX() + (random.nextDouble() - 0.5D) * 4.0D,
                wither.getY(), wither.getZ() + (random.nextDouble() - 0.5D) * 4.0D);
        skeleton.getPersistentData().putUUID(WitherTitleHelper.WITHER_OWNER_KEY, wither.getUUID());
        skeleton.finalizeSpawn(serverLevel, serverLevel.getCurrentDifficultyAt(skeleton.blockPosition()),
                MobSpawnType.MOB_SUMMONED, (SpawnGroupData) null, null);
        equipEnchanted(skeleton, EquipmentSlot.HEAD, Items.DIAMOND_HELMET, random);
        equipEnchanted(skeleton, EquipmentSlot.CHEST, Items.DIAMOND_CHESTPLATE, random);
        equipEnchanted(skeleton, EquipmentSlot.LEGS, Items.DIAMOND_LEGGINGS, random);
        equipEnchanted(skeleton, EquipmentSlot.FEET, Items.DIAMOND_BOOTS, random);
        equipEnchanted(skeleton, EquipmentSlot.MAINHAND, Items.DIAMOND_SWORD, random);
        AttributeInstance maxHealth = skeleton.getAttribute(Attributes.MAX_HEALTH);
        if (maxHealth != null) {
            maxHealth.setBaseValue(60.0D);
        }
        skeleton.setHealth(60.0F);
        // Goety 式有限生命：写入到期 gameTime（配置为 0 则永久，保持旧行为）
        int lifetime = WitherTitleConfig.servantLifetimeTicks();
        if (lifetime > 0) {
            skeleton.getPersistentData().putLong(WitherTitleHelper.WITHER_SERVANT_EXPIRE_KEY,
                    serverLevel.getGameTime() + lifetime);
        }
        // 自带增益：抗性提升I、速度II、生命恢复II（各 30 秒 = 600 tick）
        int buffTicks = 30 * 20;
        skeleton.addEffect(new MobEffectInstance(MobEffects.DAMAGE_RESISTANCE, buffTicks, 0));
        skeleton.addEffect(new MobEffectInstance(MobEffects.MOVEMENT_SPEED, buffTicks, 1));
        skeleton.addEffect(new MobEffectInstance(MobEffects.REGENERATION, buffTicks, 1));
        // 立即继承主人当前目标（setTarget 内置拒绝主人/同主仆从，安全）
        skeleton.setTarget(wither.getTarget());
        serverLevel.addFreshEntity(skeleton);
    }

