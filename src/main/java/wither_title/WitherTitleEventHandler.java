    /**
     * 尾杀阶段 tick 逻辑（由 LivingEntityMixin 的 tick 拦截调用，仅服务端）：
     * 绝对无敌 —— 冻结在死亡位置、每 tick 直写底层血量、免疫一切（die/heal/hurt/remove 均被 Mixin 拦截）
     * 阶段1（0~200 tick）：末影龙风格溶解死亡动画
     * 阶段2（第200 tick）：蓝色粒子大爆发 + 原地生成锚定蓝色黑洞
     * 阶段3（黑洞 900 tick 后）：彻底死亡，掉落"灵魂之星" + 600,000 经验
     */
    public static void tickUndefinedFinalSkill(WitherBoss wither) {
        if (!(wither.level() instanceof ServerLevel serverLevel)) return;

        Vec3 deathPos = undefinedDeathPos == Vec3.ZERO ? wither.position() : undefinedDeathPos;

        // 冻结在死亡位置：禁止一切移动/AI 行为
        wither.setDeltaMovement(Vec3.ZERO);
        wither.setPos(deathPos.x, deathPos.y, deathPos.z);
        wither.hurtTime = 0;
        wither.deathTime = 0;
        wither.setNoActionTime(0);

        // 每 tick 直写底层真实血量（对抗任何回血/直写），绝对锁血
        try {
            wither.getEntityData().set(com.enchantmentSkill.mixin.LivingEntityAccessor.shatter$getDataHealthId(), 0.3999F);
        } catch (Throwable ignored) {
        }

        // 每 tick 更新 BOSS 血条名称 —— 尾杀阶段原版 customServerAiStep 停跑，
        // 动态渐变由这里接管（服务端每 tick setName 广播到客户端）
        try {
            ((com.enchantmentSkill.mixin.WitherBossBossBarAccessor) wither).shatter$getBossEvent()
                    .setName(WitherTitleHelper.getUndefinedDisplayName());
        } catch (Throwable ignored) {
        }

        // 倒计时
        int deathTime;
        try {
            deathTime = wither.getEntityData().get(WitherTitleHelper.UNDEFINED_DEATH_TIME);
        } catch (Throwable t) {
            deathTime = WitherTitleHelper.UNDEFINED_FINAL_TOTAL_TICKS;
        }
        deathTime--;
        try {
            wither.getEntityData().set(WitherTitleHelper.UNDEFINED_DEATH_TIME, deathTime);
        } catch (Throwable ignored) {
        }
        int elapsed = WitherTitleHelper.UNDEFINED_FINAL_TOTAL_TICKS - deathTime;

        // ===== 阶段1：末影龙式溶解死亡动画（0 ~ 200）=====
        if (elapsed <= WitherTitleHelper.UNDEFINED_DISSOLVE_TICKS) {
            // 身体碎裂剥落：从凋灵身体体积（约3.5×3.5×2格）内爆出白蓝粒子
            // 前半段（0~100）粒子量递增 —— 身体逐渐崩解
            if (elapsed <= 100) {
                int burst = 6 + elapsed / 10;
                for (int i = 0; i < burst; i++) {
                    double ox = (serverLevel.getRandom().nextDouble() - 0.5D) * 3.5D;
                    double oy = serverLevel.getRandom().nextDouble() * 3.0D;
                    double oz = (serverLevel.getRandom().nextDouble() - 0.5D) * 3.5D;
                    // 白色光点（身体碎裂的"光尘"）+ 灵魂粒子
                    serverLevel.sendParticles(ParticleTypes.END_ROD,
                            deathPos.x + ox, deathPos.y + oy, deathPos.z + oz,
                            1, 0.0D, 0.0D, 0.0D, 0.0D);
                    if (i % 3 == 0) {
                        serverLevel.sendParticles(ParticleTypes.SOUL,
                                deathPos.x + ox, deathPos.y + oy, deathPos.z + oz,
                                1, 0.0D, 0.02D, 0.0D, 0.0D);
                    }
                }
            }
            // 第100 tick：本体"溶解"消失（invisible 同步客户端，只剩粒子与光柱）
            if (elapsed == 100) {
                wither.setInvisible(true);
                serverLevel.playSound(null, deathPos.x, deathPos.y, deathPos.z,
                        SoundEvents.WARDEN_SONIC_CHARGE, wither.getSoundSource(), 3.0F, 0.8F);
            }
            // 后半段（100~200）：身体已消失，粒子渐稀 + 上升余烬
            if (elapsed > 100) {
                int after = Math.max(1, 12 - (elapsed - 100) / 8);
                for (int i = 0; i < after; i++) {
                    double ox = (serverLevel.getRandom().nextDouble() - 0.5D) * 3.5D;
                    double oz = (serverLevel.getRandom().nextDouble() - 0.5D) * 3.5D;
                    serverLevel.sendParticles(ParticleTypes.END_ROD,
                            deathPos.x + ox, deathPos.y + serverLevel.getRandom().nextDouble() * 3.0D, deathPos.z + oz,
                            1, 0.0D, 0.04D, 0.0D, 0.0D);
                }
            }
            // 向上的光柱（每 tick，贯穿全程）
            serverLevel.sendParticles(ParticleTypes.END_ROD,
                    deathPos.x, deathPos.y + 1.5D, deathPos.z, 2, 0.25D, 5.0D, 0.25D, 0.0D);
            // 音效
            if (elapsed == 1) {
                serverLevel.playSound(null, deathPos.x, deathPos.y, deathPos.z,
                        SoundEvents.WITHER_DEATH, wither.getSoundSource(), 3.0F, 0.5F);
                serverLevel.playSound(null, deathPos.x, deathPos.y, deathPos.z,
                        SoundEvents.END_PORTAL_SPAWN, wither.getSoundSource(), 2.0F, 1.0F);
            }
        }

        // ===== 阶段2：动画结束 —— 蓝色粒子大爆发 + 生成锚定蓝色黑洞 =====
        if (elapsed == WitherTitleHelper.UNDEFINED_DISSOLVE_TICKS) {
            for (int i = 0; i < 400; i++) {
                double theta = serverLevel.getRandom().nextDouble() * Math.PI * 2.0D;
                double phi = Math.acos(2.0D * serverLevel.getRandom().nextDouble() - 1.0D);
                double speed = 0.4D + serverLevel.getRandom().nextDouble() * 0.8D;
                serverLevel.sendParticles(ParticleTypes.DRAGON_BREATH,
                        deathPos.x, deathPos.y + 1.5D, deathPos.z, 0,
                        Math.sin(phi) * Math.cos(theta) * speed,
                        Math.cos(phi) * speed,
                        Math.sin(phi) * Math.sin(theta) * speed, 0.0D);
            }
            serverLevel.sendParticles(ParticleTypes.SONIC_BOOM,
                    deathPos.x, deathPos.y + 1.5D, deathPos.z, 3, 0.0D, 0.0D, 0.0D, 0.0D);
            serverLevel.playSound(null, deathPos.x, deathPos.y, deathPos.z,
                    SoundEvents.GENERIC_EXPLODE, wither.getSoundSource(), 3.0F, 0.6F);
            serverLevel.playSound(null, deathPos.x, deathPos.y, deathPos.z,
                    SoundEvents.WITHER_SPAWN, wither.getSoundSource(), 1.0F, 1.5F);

            if (isIronSpellsLoaded()) {
                // 原地（y=死亡位置）生成锚定蓝色黑洞，20格吸力，持续900 tick
                spawnIronSpellsBlackHole(serverLevel, deathPos, wither);
            } else {
                // 无铁魔法：第一波音波（10~20跳 × 100，warden 音波类型）
                fireSonicBoomBarrage(serverLevel, deathPos, wither);
            }
        }

        // ===== 阶段3：黑洞结束（有铁魔法）—— 彻底死亡 =====
        if (isIronSpellsLoaded()) {
            if (deathTime <= 0) {
                trulyKillUndefinedWither(wither, serverLevel);
            }
        } else {
            // ===== 无铁魔法时间线：第一波后等 2s → 第二波（5跳×1000，damage_soul）→ 真死 =====
            if (elapsed == WitherTitleHelper.SOUL_BOOM_SECOND_WAVE_TICK) {
                fireSoulBoomWave(serverLevel, deathPos, wither);
            }
            if (elapsed >= WitherTitleHelper.UNDEFINED_FINAL_TOTAL_TICKS_NO_IRONS) {
                trulyKillUndefinedWither(wither, serverLevel);
            }
        }
    }

