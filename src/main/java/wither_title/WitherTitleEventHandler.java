    /** Returns the undefined Wither owner of a damage source, if it has one. */
    public static WitherBoss getUndefinedAttacker(DamageSource source, boolean includeSkull) {
        if (source == null) return null;
        // Skull hits are completed by the WitherSkull HEAD/TAIL snapshot pair;
        // do not also process them through the generic hurt() return hook.
        if (source.getDirectEntity() instanceof WitherSkull && !includeSkull) return null;
        if (source.getEntity() instanceof WitherBoss wither
                && WitherTitleHelper.isUndefinedWither(wither)) {
            return wither;
        }
        if (includeSkull && source.getDirectEntity() instanceof WitherSkull skull
                && skull.getOwner() instanceof WitherBoss wither
                && WitherTitleHelper.isUndefinedWither(wither)) {
            return wither;
        }
        return null;
    }

