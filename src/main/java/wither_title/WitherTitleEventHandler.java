    private static void handleOutOfCombat(WitherBoss wither, ServerLevel serverLevel) {
        if (isUndefinedDiving(wither) || !isUndefinedOutOfCombat(wither)) return;
        int minY = serverLevel.getMinBuildHeight();
        int groundY = minY;
        net.minecraft.core.BlockPos.MutableBlockPos cursor = new net.minecraft.core.BlockPos.MutableBlockPos(
                wither.getBlockX(), wither.getBlockY(), wither.getBlockZ());
        for (int y = wither.getBlockY(); y >= minY; y--) {
            cursor.setY(y);
            if (!serverLevel.getBlockState(cursor).getCollisionShape(serverLevel, cursor).isEmpty()) {
                groundY = y + 1;
                break;
            }
        }
        double height = wither.getY() - groundY;
        if (height <= OUT_OF_COMBAT_MAX_ALTITUDE) return;
        double drop = Math.min(height - OUT_OF_COMBAT_MAX_ALTITUDE, 2.5D);
        wither.noPhysics = false;
        wither.setDeltaMovement(wither.getDeltaMovement().x * 0.15D, -2.5D, wither.getDeltaMovement().z * 0.15D);
        wither.setPos(wither.getX(), Math.max(groundY, wither.getY() - drop), wither.getZ());
        wither.hasImpulse = true;
        wither.hurtMarked = true;
    }

