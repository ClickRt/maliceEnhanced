    @SubscribeEvent(priority = EventPriority.HIGHEST)
    public static void onLivingHurt(LivingHurtEvent event) {
        if (EXTRA_DAMAGE.get()) return;
        LivingEntity target = event.getEntity();
        DamageSource source = event.getSource();

        // Low-health undefined Wither attacks consume the target's food once
        // and scale the raw hit before armor/resistance are applied. Direct
        // soul attacks use the same helper at their call site; the guard keeps
        // their one-point visual feedback from entering this block again.
        if (!isUndefinedAttackGuarded()) {
            WitherBoss undefinedAttacker = getUndefinedAttacker(source, true);
            if (undefinedAttacker != null && undefinedAttacker != target) {
                float multiplier = consumeUndefinedFoodMultiplier(undefinedAttacker, target);
                event.setAmount(event.getAmount() * multiplier);
                if (source.getDirectEntity() instanceof WitherSkull) {
                    SKULL_ATTACK_MULTIPLIER.put(target.getUUID(), multiplier);
                    // The direct entity hit has a HEAD snapshot already;
                    // explosion-only splash targets create their snapshot here.
                    SKULL_ATTACK_OWNER.putIfAbsent(target.getUUID(), undefinedAttacker.getUUID());
                    SKULL_ATTACK_HEALTH.putIfAbsent(target.getUUID(), target.getHealth());
                } else {
                    HURT_ATTACK_MULTIPLIER.put(target.getUUID(), multiplier);
                }
            }
        }

        // 未定义凋灵半血后：其造成的任何伤害（俯冲近战、头颅爆炸溅射等）都给目标挂上治疗压制
        // （普通回血 -50%，setHealth/数据层直写 -80%，2s）；头颅直击另在 WitherSkullMixin 里补标记。
        // 伤害来源可能是凋灵本身（俯冲/爆炸 causing），也可能是凋灵之首（爆炸 direct）。
        WitherBoss healSuppressionAttacker = null;
        if (source.getEntity() instanceof WitherBoss wb) {
            healSuppressionAttacker = wb;
        } else if (source.getDirectEntity() instanceof WitherSkull sk && sk.getOwner() instanceof WitherBoss wb2) {
            healSuppressionAttacker = wb2;
        }
        if (healSuppressionAttacker != null && healSuppressionAttacker != target
                && WitherTitleHelper.isUndefinedWither(healSuppressionAttacker)
                && WitherTitleHelper.isAtOrBelowHalfHealth(healSuppressionAttacker)) {
            WitherTitleHelper.markHealSuppression(target);
        }

        // 未定义凋灵致命伤害拦截 - 使用 外部 Mod 风格的锁血机制
        if (target instanceof WitherBoss wither && WitherTitleHelper.isUndefinedWither(wither)) {
            // 安全检查：确保SynchedEntityData已经注册
            try {
                // 尝试访问数据，如果失败则跳过锁血检查
                wither.getEntityData().get(WitherTitleHelper.UNDEFINED_FINAL_SKILL);
            } catch (Exception e) {
                // 数据还没有注册，跳过本次锁血检查
                return;
            }

            // 检查是否已经进入尾杀阶段（通过 EntityData 判断）
            if (wither.getEntityData().get(WitherTitleHelper.UNDEFINED_FINAL_SKILL)) {
                event.setCanceled(true);
                return;
            }

            // 受伤后 30 tick 自定义无敌：后续伤害在事件层直接取消
            // （激活当 tick 放行：同 tick 多段伤害由数据层每 tick 预算分摊）
            if (WitherTitleHelper.isHurtDefendBlocking(wither)) {
                event.setCanceled(true);
                return;
            }

            // 检测致命伤害：必须用"限伤夹紧后"的伤害。
            // 事件层的 amount 是护甲结算前的原始值（LivingEntity.hurt → actuallyHurt →
            // ForgeHooks.onLivingHurt），直接拿它判断会让一刀超大伤害绕过 20 点限伤
            // 直接触发尾杀。夹紧口径与数据层 WitherTitleHealthCapMixin 保持一致：
            // 单段夹 20，且受当 tick 剩余预算约束（同 tick 多段共享 20 点，先到先得）。
            float actualDamage = Math.min(Math.min(event.getAmount(), WitherTitleConfig.hurtLimit()),
                    WitherTitleHelper.getRemainingTickBudget(wither));
            float remainingHealth = wither.getHealth() - actualDamage;
            if (remainingHealth <= 0) {
                event.setCanceled(true);

                // 记录死亡位置
                undefinedDeathPos = wither.position();

                // 立即锁血，防止客户端看到 0 血
                wither.setHealth(0.3999f);
                WitherTitleHelper.clearHurtDefend(wither);
                wither.hurtTime = 0;
                wither.deathTime = 0;
                wither.invulnerableTime = 100; // 给予短暂无敌，防止连续触发
                wither.getEntityData().set(WitherTitleHelper.UNDEFINED_FINAL_SKILL, true);
                wither.getEntityData().set(WitherTitleHelper.UNDEFINED_DEATH_TIME, WitherTitleHelper.UNDEFINED_FINAL_TOTAL_TICKS);

                // 清除装备
                wither.setItemSlot(EquipmentSlot.HEAD, ItemStack.EMPTY);
                wither.setItemSlot(EquipmentSlot.CHEST, ItemStack.EMPTY);
                wither.setItemSlot(EquipmentSlot.LEGS, ItemStack.EMPTY);
                wither.setItemSlot(EquipmentSlot.FEET, ItemStack.EMPTY);
                wither.setItemSlot(EquipmentSlot.MAINHAND, ItemStack.EMPTY);
                wither.setItemSlot(EquipmentSlot.OFFHAND, ItemStack.EMPTY);

                // 直接生成铁魔法风格的蓝色黑洞，20格吸力半径
                // 如果没有铁魔法mod则跳过生成
                if (!target.level().isClientSide) {
                    ServerLevel serverLevel = (ServerLevel) wither.level();
                    Vec3 pos = wither.position();
                    spawnIronSpellsBlackHole(serverLevel, pos, wither);
                }
                return;
            }
        }

        if (target.level().isClientSide) return;

        // 仆从凋灵骷髅被主人（或主人的凋灵之首）波及 → 免伤并清除仇恨记忆
        // 防止 HurtByTargetGoal 反咬主人（否则骷髅挡弹被打后反噬未定义凋灵）
        if (target instanceof WitherSkeleton servant
                && source.getEntity() instanceof WitherBoss owner
                && WitherTitleHelper.isWitherServant(servant, owner.getUUID())) {
            event.setCanceled(true);
            servant.setTarget(null);
            servant.setLastHurtByMob(null);
            return;
        }

        if (target instanceof WitherBoss wither) {
            int title = WitherTitleHelper.getTitleId(wither);
            boolean undefined = WitherTitleHelper.isUndefinedWither(wither);

            if (title == 1 || undefined) {
                if (source.getDirectEntity() instanceof AbstractArrow) {
                    event.setCanceled(true);
                    return;
                }
                event.setAmount(event.getAmount() * 0.9F);
            }
            if (title == 2 || undefined) {
                long now = wither.level().getGameTime();
                long last = wither.getPersistentData().getLong(T2_LAST_TELEPORT_KEY);
                if (now - last >= 20) {
                    boolean projectile = source.getDirectEntity() instanceof Projectile;
                    if (!hasPureMalice(source)
                            && !isUndefinedDiving(wither)
                            && (projectile || wither.level().getRandom().nextFloat() < 0.2F)
                            && tryTeleportAway(wither, source.getEntity())) {
                        wither.getPersistentData().putLong(T2_LAST_TELEPORT_KEY, now);
                        event.setCanceled(true);
                    }
                }
            }
            if ((title == 4 || undefined) && source.getEntity() instanceof LivingEntity attacker) {
                if (EnchantmentHelper.getEnchantmentLevel(Enchantments.SMITE, attacker) > 0) {
                    wither.getPersistentData().putLong(WitherTitleHelper.SMITE_EXPIRE_KEY,
                            wither.level().getGameTime() + 100);
                    // T11 半血恢复独立压制（1 秒 = 20 tick）
                    wither.getPersistentData().putLong(WitherTitleHelper.T11_SMITE_EXPIRE_KEY,
                            wither.level().getGameTime() + 20);
                }
            }
            // Goety 式仆从护卫：未定义凋灵被生物攻击 → 32 格内仆从立即锁定攻击者
            if (undefined && wither.level() instanceof ServerLevel sl
                    && source.getEntity() instanceof LivingEntity attacker
                    && !(attacker instanceof WitherBoss)
                    && !(attacker instanceof Player p && (p.isCreative() || p.isSpectator()))
                    && !WitherTitleHelper.isWitherServant(attacker, wither.getUUID())) {
                for (WitherSkeleton servant : sl.getEntitiesOfClass(WitherSkeleton.class,
                        wither.getBoundingBox().inflate(WitherTitleHelper.SERVANT_MANAGE_RANGE),
                        s -> WitherTitleHelper.isWitherServant(s, wither.getUUID()))) {
                    servant.setTarget(attacker);
                }
            }
        }

        if (source.getDirectEntity() instanceof WitherSkull skull
                && skull.getOwner() instanceof WitherBoss wither
                && !target.is(wither)) {
            int title = WitherTitleHelper.getTitleId(wither);
            boolean undefined = WitherTitleHelper.isUndefinedWither(wither);
            if (title == 3 || undefined) {
                target.addEffect(new MobEffectInstance(MobEffects.MOVEMENT_SLOWDOWN, 100, skull.isDangerous() ? 1 : 0), wither);
            }
            if (title == 4 || undefined) {
                if (!smiteLockout(wither)) {
                    wither.heal(2.0F);
                }
            }
            if (title == 5 || undefined) {
                if (target.level() instanceof ServerLevel serverLevel) {
                    LightningBolt lightning = EntityType.LIGHTNING_BOLT.create(serverLevel);
                    if (lightning != null) {
                        lightning.moveTo(target.getX(), target.getY(), target.getZ());
                        lightning.setVisualOnly(true);
                        if (undefined) {
                            WitherTitleHelper.setLightningColor(lightning,
                                    WitherTitleHelper.UNDEFINED_LIGHTNING_COLOR);
                        }
                        serverLevel.addFreshEntity(lightning);
                    }
                }
                EXTRA_DAMAGE.set(true);
                try {
                    target.hurt(target.damageSources().lightningBolt(), target.getMaxHealth() * 0.1F);
                } finally {
                    EXTRA_DAMAGE.set(false);
                }
            }
            if ((title == 8 || undefined) && skull.getPersistentData().getBoolean(WitherTitleHelper.FLAME_SKULL_KEY)) {
                event.setAmount(event.getAmount() * 3.0F);
            }
            if ((title == 13 || undefined) && target.isOnFire()) {
                event.setAmount(event.getAmount() * 2.0F);
            }
        }

        if (WitherTitleHelper.isMarkedBySingularity(target)) {
            event.setAmount(event.getAmount() * 1.5F);
        }
    }

