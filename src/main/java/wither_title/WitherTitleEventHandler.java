    /** Applies the direct soul part; the follow-up check waits for onHit's explosion. */
    public static void finishUndefinedSkullHit(WitherBoss wither, LivingEntity target, float soulDamage) {
        if (wither == null || target == null || !WitherTitleHelper.isUndefinedWither(wither)) return;
        Float before = SKULL_ATTACK_HEALTH.get(target.getUUID());
        Float multiplier = SKULL_ATTACK_MULTIPLIER.get(target.getUUID());
        if (multiplier == null) {
            multiplier = consumeUndefinedFoodMultiplier(wither, target);
            SKULL_ATTACK_MULTIPLIER.put(target.getUUID(), multiplier);
        }
        final float factor = multiplier;
        final float healthBefore = before != null ? before : target.getHealth();
        SKULL_ATTACK_INTENDED.put(target.getUUID(), soulDamage * factor);
        performUndefinedAction(wither, target, soulDamage, factor,
                damage -> SoulSwordEventHandler.applyUndefinedSoulDamage(target, wither, damage));
    }

    /** Completes all skull snapshots after WitherSkull's explosion has run. */
    public static void completeUndefinedSkullHits(WitherBoss wither) {
        if (wither == null || !(wither.level() instanceof ServerLevel serverLevel)) return;
        List<UUID> targets = new java.util.ArrayList<>();
        for (Map.Entry<UUID, UUID> entry : SKULL_ATTACK_OWNER.entrySet()) {
            if (wither.getUUID().equals(entry.getValue())) targets.add(entry.getKey());
        }
        for (UUID targetId : targets) {
            Entity entity = serverLevel.getEntity(targetId);
            if (entity instanceof LivingEntity target) {
                Float before = SKULL_ATTACK_HEALTH.remove(targetId);
                Float multiplier = SKULL_ATTACK_MULTIPLIER.remove(targetId);
                Float intended = SKULL_ATTACK_INTENDED.remove(targetId);
                SKULL_ATTACK_OWNER.remove(targetId);
                if (before != null) finishUndefinedAttack(wither, target, before,
                        multiplier != null ? multiplier : 1.0F,
                        intended != null ? intended : Float.NaN);
            } else {
                SKULL_ATTACK_HEALTH.remove(targetId);
                SKULL_ATTACK_MULTIPLIER.remove(targetId);
                SKULL_ATTACK_INTENDED.remove(targetId);
                SKULL_ATTACK_OWNER.remove(targetId);
            }
        }
    }

