    private static void handleUndefinedWitherTick(WitherBoss wither, ServerLevel serverLevel) {
        keepUndefinedChunkLoaded(wither, serverLevel);
        try {
            if (!Boolean.TRUE.equals(wither.getEntityData().get(WitherTitleHelper.UNDEFINED_DATA))) {
                wither.getEntityData().set(WitherTitleHelper.UNDEFINED_DATA, true);
            }
        } catch (Exception ignored) {
        }
        // 尾杀阶段由 WitherBossMixin.tick 完全接管（禁止行动 + 溶解动画 + 黑洞 + 真死）
        try {
            if (wither.getEntityData().get(WitherTitleHelper.UNDEFINED_FINAL_SKILL)) return;
        } catch (Exception e) {
            return;
        }

        WitherTitleHelper.tickHurtDefend(wither);
        WitherTitleHelper.enforceMaxHealth(wither);
        float hidden = WitherTitleHelper.getHiddenHp(wither);
        float display;
        try {
            display = wither.getEntityData().get(com.enchantmentSkill.mixin.LivingEntityAccessor.shatter$getDataHealthId());
        } catch (Throwable t) {
            display = hidden;
        }
        if (display + 0.01F < hidden) {
            WitherTitleHelper.restoreDisplayHealth(wither, hidden);
            WitherTitleHelper.clearExternalHealthDelta(wither);
        } else {
            WitherTitleHelper.restoreDisplayHealth(wither, hidden);
        }

        if (hidden <= 0.5F) {
            triggerUndefinedLockHealth(wither);
            return;
        }

        // 防御机制：自动对产生仇恨的实体产生仇恨（每秒检查一次）
        if (wither.tickCount % 20 == 0) {
            handleAggroReflection(wither, serverLevel);
        }
        applyChallengeZone(wither, serverLevel);
        tryFarDive(wither);
        // 结界/僵局主动脱困：16 格内持续有"赖着不死"实体满 5s → 主动大范围瞬移跑路
        handleBarrierStuckEscape(wither, serverLevel);

        // T1: 护甲/韧性加成（每秒）
        if (wither.tickCount % 20 == 0) {
            applyT1Armor(wither);
        }

        // T1: 粒子护盾（每 2 秒）
        if (wither.tickCount % 40 == 0) {
            WitherTitleHelper.spawnSphereParticles(serverLevel, wither, ParticleTypes.END_ROD, 2.2D, 16, 0.02D);
        }

        // T10: 集束火箭 —— 发射凋零之首的频率加快 100%
        handleTitle10Cluster(wither);

        // T6: 半血时爆炸 + 召唤凋灵骷髅
        handleT6SustainUndefined(wither, serverLevel);

        // T11: 半血时每秒恢复 10 点生命值（受亡灵杀手独立压制 1 秒）
        if (wither.tickCount % 20 == 0 && wither.isPowered()) {
            long t11SmiteExpire = wither.getPersistentData().getLong(WitherTitleHelper.T11_SMITE_EXPIRE_KEY);
            long now = wither.level().getGameTime();
            if (t11SmiteExpire > now) {
                // 被亡灵杀手压制期间（1 秒内）：每秒回 (10 - 附魔等级) 血
                int smiteLevel = 0;
                // 查找 32 格内最高亡灵杀手等级
                for (LivingEntity attacker : wither.level().getEntitiesOfClass(LivingEntity.class, wither.getBoundingBox().inflate(32.0))) {
                    int lvl = EnchantmentHelper.getEnchantmentLevel(Enchantments.SMITE, attacker);
                    if (lvl > smiteLevel) smiteLevel = lvl;
                }
                // 保险锁：附魔等级上限按 6 算（防止指令获取 >5 级附魔）
                int cappedSmite = Math.min(smiteLevel, 6);
                float healAmount = Math.max(4, 10 - cappedSmite);
                wither.heal(healAmount);
            } else {
                wither.heal(10.0F);
            }
        }
    }

    /**
     * 防御机制：自动对产生仇恨的实体产生仇恨
     * 检测64格内对未定义凋灵有仇恨的实体，未定义凋灵也对它们产生仇恨
     * 排除创造模式玩家
     */
    private static void handleAggroReflection(WitherBoss wither, ServerLevel serverLevel) {
        // 如果未定义凋灵已经有目标，跳过
        if (wither.getTarget() != null) return;

        // 检查128格范围内的实体
        AABB aggroRange = wither.getBoundingBox().inflate(128.0D);
        List<LivingEntity> nearbyEntities = serverLevel.getEntitiesOfClass(
                LivingEntity.class, aggroRange,
                e -> e.isAlive() && !(e instanceof WitherBoss));

        LivingEntity nearestAttacker = null;
        double nearestDist = Double.MAX_VALUE;

        for (LivingEntity entity : nearbyEntities) {
            // 排除创造/旁观模式玩家（旁观玩家不可被选为目标）
            if (entity instanceof Player player && (player.isCreative() || player.isSpectator())) {
                continue;
            }
            // 排除自己的仆从骷髅（杜绝仆从被误记为仇恨源）
            if (entity instanceof WitherSkeleton servant && WitherTitleHelper.isWitherServant(servant, wither.getUUID())) {
                continue;
            }

            // 检查实体是否对未定义凋灵有仇恨
            boolean isAggro = false;

            // 检查1：实体的目标是未定义凋灵（Mob类型）
            if (entity instanceof net.minecraft.world.entity.Mob mob) {
                if (mob.getTarget() == wither) {
                    isAggro = true;
                }
            }

            // 检查2：玩家正在攻击未定义凋灵（主手或副手持武器，且在攻击范围内）
            if (entity instanceof Player player) {
                // 玩家对未定义凋灵造成过伤害（通过 lastHurtMob 判断）
                if (player.getLastHurtMob() == wither) {
                    isAggro = true;
                }
                // 玩家正在看向未定义凋灵且距离很近（简化检测）
                double dist = player.distanceTo(wither);
                if (dist < 10.0D && player.getAttackStrengthScale(0.5F) > 0.9F) {
                    // 玩家有攻击准备且距离近，可能在攻击
                    isAggro = true;
                }
            }

            // 检查3：实体最近对未定义凋灵造成过伤害（任何LivingEntity）
            if (entity.getLastHurtMob() == wither) {
                isAggro = true;
            }

            // 如果检测到仇恨，记录最近的攻击者
            if (isAggro) {
                double dist = entity.distanceTo(wither);
                if (dist < nearestDist) {
                    nearestDist = dist;
                    nearestAttacker = entity;
                }
            }
        }

        // 如果找到攻击者，未定义凋灵对最近的攻击者产生仇恨
        if (nearestAttacker != null) {
            wither.setTarget(nearestAttacker);
        }
    }

