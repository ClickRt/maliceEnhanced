    private static void handleT6SustainUndefined(WitherBoss wither, ServerLevel serverLevel) {
        // 每只凋零仅触发一次：首次半血 → 大爆炸 + 召唤 4 只仆从凋灵骷髅
        if (!wither.getPersistentData().getBoolean(WitherTitleHelper.T6_FIRED_KEY)) {
            if (wither.getHealth() > wither.getMaxHealth() * 0.5F) return;
            wither.getPersistentData().putBoolean(WitherTitleHelper.T6_FIRED_KEY, true);

            // 大爆炸
            serverLevel.explode(wither, wither.position().x, wither.position().y, wither.position().z, 7.0F, Level.ExplosionInteraction.MOB);

            for (int i = 0; i < 4; i++) {
                summonWitherSkeleton(wither);
            }
        }

        // 仆从管理（Goety 式）：每 SERVANT_MANAGE_INTERVAL tick 扫描一次——寿命到期消散 + 继承主人仇恨
        if (wither.tickCount % WitherTitleHelper.SERVANT_MANAGE_INTERVAL == 0) {
            LivingEntity masterTarget = wither.getTarget();
            AABB manageRange = wither.getBoundingBox().inflate(WitherTitleHelper.SERVANT_MANAGE_RANGE);
            for (WitherSkeleton servant : serverLevel.getEntitiesOfClass(WitherSkeleton.class, manageRange,
                    s -> WitherTitleHelper.isWitherServant(s, wither.getUUID()))) {
                tickServantLifetime(servant);
                if (!servant.isRemoved()) {
                    inheritMasterTarget(servant, wither, masterTarget);
                }
            }
        }

        // 自身 10 格内存在 >=1 只该凋零的仆从骷髅 → 每秒恢复 1 点生命值
        if (wither.tickCount % 20 == 0) {
            AABB range = wither.getBoundingBox().inflate(10.0D);
            List<WitherSkeleton> skeletons = serverLevel.getEntitiesOfClass(WitherSkeleton.class, range,
                    s -> WitherTitleHelper.isWitherServant(s, wither.getUUID()));
            if (!skeletons.isEmpty()) {
                wither.heal(1.0F);
            }
        }
    }

