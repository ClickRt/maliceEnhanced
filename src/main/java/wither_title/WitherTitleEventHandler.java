    private static boolean tryTeleportAway(WitherBoss wither, Entity attacker) {
        Vec3 dest = findTeleportDest(wither, attacker);
        if (dest == null) return false;
        Vec3 from = wither.position();
        AABB destBox = wither.getBoundingBox().move(dest.x - wither.getX(), dest.y - wither.getY(), dest.z - wither.getZ());
        if (!wither.level().noCollision(wither, destBox)) return false;
        wither.teleportTo(dest.x, dest.y, dest.z);
        if (wither.level() instanceof ServerLevel serverLevel) {
            double fromY = from.y + wither.getBbHeight() * 0.5D;
            double destY = dest.y + wither.getBbHeight() * 0.5D;
            for (int i = 0; i <= 16; i++) {
                double t = i / 16.0D;
                serverLevel.sendParticles(ParticleTypes.PORTAL,
                        Mth.lerp(t, from.x, dest.x), Mth.lerp(t, fromY, destY), Mth.lerp(t, from.z, dest.z),
                        2, 0.08D, 0.08D, 0.08D, 0.0D);
            }
            serverLevel.sendParticles(ParticleTypes.LARGE_SMOKE,
                    from.x, from.y + 1.0D, from.z, 20, 0.4D, 0.8D, 0.4D, 0.02D);
            serverLevel.sendParticles(ParticleTypes.PORTAL,
                    dest.x, destY, dest.z, 40, 0.4D, 1.0D, 0.4D, 0.3D);
        }
        wither.level().playSound(null, wither.getX(), wither.getY(), wither.getZ(),
                SoundEvents.ENDERMAN_TELEPORT, wither.getSoundSource(), 1.0F, 1.0F);
        return true;
    }

    private static Vec3 findTeleportDest(WitherBoss wither, Entity attacker) {
        RandomSource random = wither.level().getRandom();
        boolean hasAway = false;
        Vec3 away = Vec3.ZERO;
        if (attacker != null && attacker.distanceTo(wither) > 0.1D) {
            away = new Vec3(wither.getX() - attacker.getX(), 0, wither.getZ() - attacker.getZ()).normalize();
            hasAway = away.lengthSqr() > 1.0E-4D;
        }
        for (int i = 0; i < 32; i++) {
            double dx;
            double dz;
            if (hasAway) {
                double angle = (random.nextDouble() - 0.5D) * (Math.PI * 0.75D);
                double cos = Math.cos(angle);
                double sin = Math.sin(angle);
                dx = away.x * cos - away.z * sin;
                dz = away.x * sin + away.z * cos;
            } else {
                double angle = random.nextDouble() * Math.PI * 2.0D;
                dx = Math.cos(angle);
                dz = Math.sin(angle);
            }
            double dist = 8.0D + random.nextDouble() * 8.0D;
            double x = wither.getX() + dx * dist;
            double z = wither.getZ() + dz * dist;
            double y = wither.getY() + (random.nextInt(9) - 4);
            AABB box = wither.getBoundingBox().move(x - wither.getX(), y - wither.getY(), z - wither.getZ());
            if (wither.level().noCollision(wither, box)) {
                return new Vec3(x, y, z);
            }
        }
        return null;
    }

    // ==================== 结界/僵局主动脱困瞬移 ====================

    /**
     * 未定义凋灵的主动越障/脱困：若自身 16 格内持续存在"赖着不死的 Boss"（**在 {@code forge:bosses} 标签内**、
     * 血量≤{@link #REFUSE_DEATH_HEALTH} 且仍活着），累计满 {@link #STUCK_TELEPORT_TICKS}（5 秒）后，
     * 主动以自身为中心做 32~48 格大范围随机瞬移跑路（区别于受击瞬移的"绕攻击者 8~16 格环"，
     * 这样才跳得出结界覆盖）。俯冲阶段不计数；有独立冷却防刷屏。
     */
    private static void handleBarrierStuckEscape(WitherBoss wither, ServerLevel serverLevel) {
        // 俯冲中不计数，避免与俯冲虚化/既有闪避逻辑冲突
        if (isUndefinedDiving(wither)) {
            if (wither.getPersistentData().getInt(UNDEFINED_STUCK_TICKS_KEY) != 0) {
                wither.getPersistentData().putInt(UNDEFINED_STUCK_TICKS_KEY, 0);
            }
            return;
        }
        boolean trapped = false;
        for (LivingEntity e : serverLevel.getEntitiesOfClass(LivingEntity.class,
                wither.getBoundingBox().inflate(STUCK_SCAN_RADIUS),
                ent -> ent != wither && !(ent instanceof Player) && !(ent instanceof WitherBoss)
                        && !WitherTitleHelper.isWitherServant(ent, wither.getUUID())
                        && ent.getType().is(UNDEFINED_STUCK_BOSS_TAG))) {
            if (isRefusingToDie(e)) {
                trapped = true;
                break;
            }
        }
        int stuck = wither.getPersistentData().getInt(UNDEFINED_STUCK_TICKS_KEY);
        if (!trapped) {
            if (stuck != 0) wither.getPersistentData().putInt(UNDEFINED_STUCK_TICKS_KEY, 0);
            return;
        }
        stuck++;
        wither.getPersistentData().putInt(UNDEFINED_STUCK_TICKS_KEY, stuck);
        if (stuck < STUCK_TELEPORT_TICKS) return;
        // 满 5 秒：遵守冷却，冷却未结束就停在阈值，下一有隙立刻走
        long now = serverLevel.getGameTime();
        long last = wither.getPersistentData().getLong(T2_LAST_TELEPORT_KEY);
        if (now - last < STUCK_TELEPORT_COOLDOWN) return;
        if (fleeTeleport(wither, serverLevel)) {
            wither.getPersistentData().putLong(T2_LAST_TELEPORT_KEY, now);
        }
        wither.getPersistentData().putInt(UNDEFINED_STUCK_TICKS_KEY, 0);
    }

    /** 泛用判定：活着但血量贴地赖着不死（持续 5 秒满足，普通怪早死或被补刀，只有被强行续命才会赖这么久）。 */
    private static boolean isRefusingToDie(LivingEntity e) {
        return e.isAlive() && !e.isRemoved() && e.getHealth() <= REFUSE_DEATH_HEALTH;
    }

    /** 以自身为中心的大范围逃跑瞬移（落点 noCollision 才走），带与受击瞬移一致的粒子/音效。 */
    private static boolean fleeTeleport(WitherBoss wither, ServerLevel serverLevel) {
        Vec3 dest = findFleeDest(wither);
        if (dest == null) return false;
        Vec3 from = wither.position();
        AABB destBox = wither.getBoundingBox().move(dest.x - wither.getX(), dest.y - wither.getY(), dest.z - wither.getZ());
        if (!wither.level().noCollision(wither, destBox)) return false;
        wither.teleportTo(dest.x, dest.y, dest.z);
        double fromY = from.y + wither.getBbHeight() * 0.5D;
        double destY = dest.y + wither.getBbHeight() * 0.5D;
        for (int i = 0; i <= 16; i++) {
            double t = i / 16.0D;
            serverLevel.sendParticles(ParticleTypes.PORTAL,
                    Mth.lerp(t, from.x, dest.x), Mth.lerp(t, fromY, destY), Mth.lerp(t, from.z, dest.z),
                    2, 0.08D, 0.08D, 0.08D, 0.0D);
        }
        serverLevel.sendParticles(ParticleTypes.LARGE_SMOKE,
                from.x, from.y + 1.0D, from.z, 20, 0.4D, 0.8D, 0.4D, 0.02D);
        serverLevel.sendParticles(ParticleTypes.PORTAL,
                dest.x, destY, dest.z, 40, 0.4D, 1.0D, 0.4D, 0.3D);
        wither.level().playSound(null, wither.getX(), wither.getY(), wither.getZ(),
                SoundEvents.ENDERMAN_TELEPORT, wither.getSoundSource(), 1.0F, 1.0F);
        return true;
    }

    /** 先在 32~48 格环采样，全部被占则退到 16~24 格再试一轮，尽量跳出结界。 */
    private static Vec3 findFleeDest(WitherBoss wither) {
        RandomSource random = wither.level().getRandom();
        Vec3 far = sampleFleeRing(wither, random, 32.0D, 48.0D, 6);
        return far != null ? far : sampleFleeRing(wither, random, 16.0D, 24.0D, 4);
    }

    private static Vec3 sampleFleeRing(WitherBoss wither, RandomSource random,
                                       double minDist, double maxDist, int yJitter) {
        for (int i = 0; i < 48; i++) {
            double angle = random.nextDouble() * Math.PI * 2.0D;
            double dist = minDist + random.nextDouble() * (maxDist - minDist);
            double x = wither.getX() + Math.cos(angle) * dist;
            double z = wither.getZ() + Math.sin(angle) * dist;
            double y = wither.getY() + (random.nextInt(2 * yJitter + 1) - yJitter);
            AABB box = wither.getBoundingBox().move(x - wither.getX(), y - wither.getY(), z - wither.getZ());
            if (wither.level().noCollision(wither, box)) {
                return new Vec3(x, y, z);
            }
        }
        return null;
    }

    // ==================== 服务端 tick ====================

    @SubscribeEvent
    public static void onServerTick(TickEvent.ServerTickEvent event) {
        if (event.phase != TickEvent.Phase.END) return;
        MinecraftServer server = event.getServer();
        if (server == null) return;
        long gameTime = server.overworld().getGameTime();
        releaseFlightOutsideChallenge(server);
        WitherTitleHelper.cleanupStaleMarks(gameTime);
        if (gameTime % 200 == 0 && !COOLDOWN_SNAPSHOT.isEmpty()) {
            COOLDOWN_SNAPSHOT.keySet().removeIf(uuid -> {
                Entity e = server.overworld().getEntity(uuid);
                return e == null || e.isRemoved();
            });
        }
        if (gameTime % 200 == 0 && !WITHER_DIVE.isEmpty()) {
            WITHER_DIVE.entrySet().removeIf(entry -> {
                for (ServerLevel level : server.getAllLevels()) {
                    Entity e = level.getEntity(entry.getKey());
                    if (e != null && !e.isRemoved()) return false;
                }
                return true;
            });
        }
        if (gameTime % 200 == 0) {
            // A skull can be removed between the HEAD and TAIL injections;
            // discard any orphaned snapshots so long-lived servers do not
            // retain target UUIDs forever.
            SKULL_ATTACK_MULTIPLIER.clear();
            SKULL_ATTACK_HEALTH.clear();
            SKULL_ATTACK_OWNER.clear();
            HURT_ATTACK_MULTIPLIER.clear();
        }
    }

    // ==================== 下界之星 tooltip ====================

    @SubscribeEvent
    public static void onItemTooltip(ItemTooltipEvent event) {
        ItemStack stack = event.getItemStack();
        if (stack.getItem() instanceof StarCoronaCrystalItem
                && StarCoronaCurios.isEquippedStack(event.getEntity(), stack)) {
            List<Component> tooltip = event.getToolTip();
            // Keep the item name and replace the dozens of title-description lines with a compact summary.
            if (tooltip.size() > 1) tooltip.subList(1, tooltip.size()).clear();
            StarCoronaInventory inventory = StarCoronaInventory.of(stack);
            tooltip.add(Component.translatable("item.malice_enhanced.star_corona_crystal.compact",
                    inventory.titleCount(), StarCrystalSlots.TITLE_SLOTS).withStyle(ChatFormatting.GRAY));
            for (int i = 0; i < StarCrystalSlots.TITLE_SLOTS; i++) {
                int title = StarCrystalSlots.getTitleId(inventory.getStackInSlot(i));
                if (title <= 0) continue;
                tooltip.add(Component.translatable("item.malice_enhanced.star_corona_crystal.compact_line",
                                WitherTitleHelper.getTitleName(title),
                                Component.translatable("item.malice_enhanced.star_corona_crystal.compact_effect." + title))
                        .withStyle(ChatFormatting.GRAY));
            }
            if (inventory.hasAllTitles()) {
                tooltip.add(Component.translatable("item.malice_enhanced.star_corona_crystal.ascension")
                        .withStyle(ChatFormatting.LIGHT_PURPLE));
            }
            if (inventory.hasSoulHeart()) {
                tooltip.add(Component.translatable("item.malice_enhanced.star_corona_crystal.compact_soul_heart")
                        .withStyle(ChatFormatting.AQUA));
            }
            return;
        }
        if (!stack.is(Items.NETHER_STAR) || !stack.hasTag()) return;
        CompoundTag tag = stack.getTag();
        if (tag == null || !tag.contains(WitherTitleHelper.STAR_NBT_KEY)) return;
        int id = tag.getInt(WitherTitleHelper.STAR_NBT_KEY);
        if (id < WitherTitleHelper.MIN_TITLE || id > WitherTitleHelper.MAX_TITLE) return;
        event.getToolTip().add(1, Component.translatable("wither_title.malice_enhanced.star_tooltip",
                        WitherTitleHelper.getTitleName(id))
                .withStyle(ChatFormatting.DARK_PURPLE));
        event.getToolTip().add(2, Component.translatable("wither_title.malice_enhanced." + id + ".desc")
                .withStyle(ChatFormatting.GRAY));
    }

