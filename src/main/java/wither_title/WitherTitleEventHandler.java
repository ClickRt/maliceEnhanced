    private static void handleTitle10Cluster(WitherBoss wither) {
        int[] next = ((WitherBossAccessor) wither).getNextHeadUpdate();
        int[] snap = COOLDOWN_SNAPSHOT.computeIfAbsent(wither.getUUID(), k -> new int[2]);
        for (int i = 0; i < next.length; i++) {
            int cur = next[i];
            int remaining = cur - wither.tickCount;
            if (remaining > 0 && snap[i] != cur) {
                if (WitherTitleHelper.isUndefinedWither(wither) && isUndefinedCharging(wither)) {
                    cur = wither.tickCount + remaining * 5 / 2;
                } else {
                    cur = wither.tickCount + remaining / 2;
                }
                next[i] = cur;
            }
            snap[i] = cur;
        }
    }

